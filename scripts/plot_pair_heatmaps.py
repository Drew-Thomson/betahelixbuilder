#!/usr/bin/env python3
"""Plot beta-helix pairwise interaction heatmaps and L-vs-D parity scatter charts."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


CHEM_GROUP_ORDER: list[str] = [
    "G", "A", "V", "L", "I", "M", "P",
    "F", "Y", "W",
    "S", "T", "N", "Q",
    "C", "H",
    "D", "E",
    "K", "R",
]

GROUP_BOUNDARIES: list[int] = [7, 10, 14, 16, 18]

METRIC_LABELS: dict[str, str] = {
    "ddE_dmc": r"$\Delta\Delta E_{\mathrm{DMC}}$ (BUDEFF)",
    "dE_vs_ala": r"$\Delta E_{\mathrm{Ala}}$ (BUDEFF)",
    "direct_total": r"$E_{\mathrm{direct}}(i, j)$ (BUDEFF)",
    "direct_sc_total": r"$E_{\mathrm{direct,SC}}(i, j)$ (BUDEFF)",
}


def load_pair_table(
    csv_path: Path,
    metric: str,
) -> tuple[list[str], dict[tuple[str, int], np.ndarray]]:
    """Load tidy pairwise CSV output into indexed `(N, N)` score matrices.

    Parameters
    ----------
    csv_path : Path
        Path to the tidy CSV generated by ``betahelixbuilder probe-pairs``.
    metric : str
        Scalar column name to extract (e.g., ``"ddE_dmc"``).

    Returns
    -------
    residues : list[str]
        Ordered one-letter residue codes along rows and columns, length ``N``.
    matrices : dict[tuple[str, int], np.ndarray]
        Mapping from ``(anchor, offset)`` to an ``np.ndarray`` of shape ``(N, N)``,
        where entry ``[a, b]`` corresponds to ``res_i = residues[a]`` at anchor
        and ``res_j = residues[b]`` at ``anchor + offset``.
    """
    records: list[tuple[str, int, str, str, float]] = []
    present_codes: set[str] = set()

    with csv_path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames is None or metric not in reader.fieldnames:
            raise ValueError(f"Column '{metric}' not found in {csv_path}")
        for row in reader:
            anchor = row["anchor"].strip()
            offset = int(row["offset"])
            ri = row["res_i"].strip()
            rj = row["res_j"].strip()
            val = float(row[metric])
            records.append((anchor, offset, ri, rj, val))
            present_codes.add(ri)
            present_codes.add(rj)

    residues = [code for code in CHEM_GROUP_ORDER if code in present_codes]
    extra = sorted(present_codes.difference(residues))
    residues.extend(extra)
    n_res = len(residues)
    if n_res == 0:
        raise ValueError(f"No residue rows found in {csv_path}")

    code_to_idx: dict[str, int] = {code: idx for idx, code in enumerate(residues)}
    grouped: dict[tuple[str, int], list[tuple[int, int, float]]] = {}
    for anchor, offset, ri, rj, val in records:
        grouped.setdefault((anchor, offset), []).append(
            (code_to_idx[ri], code_to_idx[rj], val)
        )

    matrices: dict[tuple[str, int], np.ndarray] = {}
    for key, entries in grouped.items():
        mat = np.full((n_res, n_res), np.nan, dtype=np.float64)
        idx_arr = np.asarray(entries, dtype=np.float64)
        rows_idx = idx_arr[:, 0].astype(np.intp)
        cols_idx = idx_arr[:, 1].astype(np.intp)
        mat[rows_idx, cols_idx] = idx_arr[:, 2]
        matrices[key] = mat

    return residues, matrices


def compute_color_limits(
    arrays: list[np.ndarray],
    clip_percentile: float,
    vmin_override: float | None,
    vmax_override: float | None,
) -> tuple[float, float]:
    """Compute finite color-bar limits across one or more `(N, N)` score arrays.

    Parameters
    ----------
    arrays : list[np.ndarray]
        Sequence of score matrices, each of shape ``(N, N)``.
    clip_percentile : float
        Upper percentile in ``(0, 100]`` used to cap extreme steric clashes so
        favorable negative minima remain clearly resolved.
    vmin_override : float | None
        Explicit minimum color limit.
    vmax_override : float | None
        Explicit maximum color limit.

    Returns
    -------
    tuple[float, float]
        ``(vmin, vmax)`` with ``vmax > vmin``.
    """
    finite_chunks = [arr[np.isfinite(arr)] for arr in arrays]
    finite_vals = np.concatenate([c for c in finite_chunks if c.size > 0])
    if finite_vals.size == 0:
        return (-1.0, 1.0)

    vmin = float(np.min(finite_vals)) if vmin_override is None else float(vmin_override)
    if vmax_override is not None:
        vmax = float(vmax_override)
    elif clip_percentile < 100.0:
        vmax = float(np.percentile(finite_vals, clip_percentile))
    else:
        vmax = float(np.max(finite_vals))

    if vmax <= vmin:
        vmax = vmin + 1e-6
    return vmin, vmax


def annotate_heatmap(
    ax: plt.Axes,
    matrix: np.ndarray,
    residues: list[str],
    cmap: str,
    vmin: float,
    vmax: float,
    annotate: bool,
    title: str,
    xlabel: str,
    ylabel: str,
) -> matplotlib.image.AxesImage:
    """Render a single `(N, N)` residue-pair heatmap onto a Matplotlib axes.

    Parameters
    ----------
    ax : plt.Axes
        Target axes instance.
    matrix : np.ndarray
        Pairwise score matrix of shape ``(N, N)``.
    residues : list[str]
        Residue one-letter labels of length ``N``.
    cmap : str
        Matplotlib colormap name (colorblind-friendly default: ``"cividis"``).
    vmin : float
        Minimum color limit.
    vmax : float
        Maximum color limit.
    annotate : bool
        Overlay numeric values in cells when ``N <= 20``.
    title : str
        Axes title.
    xlabel : str
        X-axis label.
    ylabel : str
        Y-axis label.

    Returns
    -------
    matplotlib.image.AxesImage
        Image handle for shared or individual colorbars.
    """
    cmap_obj = plt.get_cmap(cmap).copy()
    cmap_obj.set_bad(color="#dddddd")
    img = ax.imshow(
        matrix,
        cmap=cmap_obj,
        vmin=vmin,
        vmax=vmax,
        aspect="equal",
        interpolation="nearest",
    )

    n_res = len(residues)
    ticks = np.arange(n_res)
    ax.set_xticks(ticks)
    ax.set_yticks(ticks)
    ax.set_xticklabels(residues, fontsize=8)
    ax.set_yticklabels(residues, fontsize=8)
    ax.set_xlabel(xlabel, fontsize=10)
    ax.set_ylabel(ylabel, fontsize=10)
    ax.set_title(title, fontsize=11)

    active_boundaries = [
        idx - 0.5 for idx in GROUP_BOUNDARIES if 0 < idx < n_res and residues[:len(CHEM_GROUP_ORDER)] == CHEM_GROUP_ORDER[:len(residues)]
    ]
    for b in active_boundaries:
        ax.axhline(b, color="white", linewidth=0.8, alpha=0.7)
        ax.axvline(b, color="white", linewidth=0.8, alpha=0.7)

    if annotate and n_res <= 20:
        norm = matplotlib.colors.Normalize(vmin=vmin, vmax=vmax, clip=True)
        rgba = cmap_obj(norm(np.nan_to_num(matrix, nan=0.0)))
        # Perceived luminance threshold for readable overlay text
        lum = 0.2126 * rgba[:, :, 0] + 0.7152 * rgba[:, :, 1] + 0.0722 * rgba[:, :, 2]
        fontsize = 6 if n_res > 12 else 8
        for i in range(n_res):
            for j in range(n_res):
                val = matrix[i, j]
                if not np.isfinite(val):
                    continue
                txt_color = "#111111" if lum[i, j] > 0.55 else "#f8f8f8"
                ax.text(
                    j,
                    i,
                    f"{val:.1f}",
                    ha="center",
                    va="center",
                    color=txt_color,
                    fontsize=fontsize,
                )

    return img


def plot_single_heatmaps(
    residues: list[str],
    matrices: dict[tuple[str, int], np.ndarray],
    output_dir: Path,
    metric: str,
    metric_label: str,
    cmap: str,
    clip_percentile: float,
    vmin_override: float | None,
    vmax_override: float | None,
    annotate: bool,
) -> list[Path]:
    """Write individual heatmap PNG files for each `(anchor, offset)` panel.

    Parameters
    ----------
    residues : list[str]
        Residue one-letter labels of length ``N``.
    matrices : dict[tuple[str, int], np.ndarray]
        Mapping of ``(anchor, offset)`` -> ``(N, N)`` matrix.
    output_dir : Path
        Destination directory.
    metric : str
        Metric column name.
    metric_label : str
        Human-readable colorbar label.
    cmap : str
        Colormap name.
    clip_percentile : float
        Upper clipping percentile.
    vmin_override : float | None
        Explicit minimum bound.
    vmax_override : float | None
        Explicit maximum bound.
    annotate : bool
        Overlay numeric values inside matrix cells.

    Returns
    -------
    list[Path]
        Paths to written heatmap image files.
    """
    saved: list[Path] = []
    for (anchor, offset), mat in sorted(matrices.items(), key=lambda item: (item[0][0], item[0][1])):
        vmin, vmax = compute_color_limits([mat], clip_percentile, vmin_override, vmax_override)
        fig, ax = plt.subplots(figsize=(7.5, 6.5), dpi=180)
        sign_off = f"{offset:+d}"
        img = annotate_heatmap(
            ax=ax,
            matrix=mat,
            residues=residues,
            cmap=cmap,
            vmin=vmin,
            vmax=vmax,
            annotate=annotate,
            title=f"Beta-Helix Pairwise {metric} | Anchor={anchor}, Offset $i \\to i{sign_off}$",
            xlabel=f"Partner residue at $i{sign_off}$",
            ylabel="Anchor residue at $i$",
        )
        cbar = fig.colorbar(img, ax=ax, fraction=0.046, pad=0.04)
        cbar.set_label(metric_label, fontsize=10)
        fig.tight_layout()

        off_slug = f"p{offset}" if offset >= 0 else f"m{abs(offset)}"
        out_path = output_dir / f"heatmap_{metric}_{anchor}_{off_slug}.png"
        fig.savefig(out_path)
        plt.close(fig)
        saved.append(out_path)
    return saved


def plot_overview_grid(
    residues: list[str],
    matrices: dict[tuple[str, int], np.ndarray],
    output_dir: Path,
    metric: str,
    metric_label: str,
    cmap: str,
    clip_percentile: float,
    vmin_override: float | None,
    vmax_override: float | None,
) -> Path | None:
    """Write a combined multi-panel grid across all anchors and offsets with shared color scale."""
    anchors = sorted({anchor for anchor, _ in matrices.keys()})
    offsets = sorted({offset for _, offset in matrices.keys()})
    if not anchors or not offsets:
        return None

    vmin, vmax = compute_color_limits(
        list(matrices.values()), clip_percentile, vmin_override, vmax_override
    )
    n_rows = len(anchors)
    n_cols = len(offsets)
    fig, axes = plt.subplots(
        n_rows,
        n_cols,
        figsize=(4.2 * n_cols + 1.0, 4.1 * n_rows + 0.8),
        dpi=180,
        squeeze=False,
    )

    last_img = None
    for r_idx, anchor in enumerate(anchors):
        for c_idx, offset in enumerate(offsets):
            ax = axes[r_idx, c_idx]
            mat = matrices.get((anchor, offset))
            if mat is None:
                ax.set_visible(False)
                continue
            sign_off = f"{offset:+d}"
            last_img = annotate_heatmap(
                ax=ax,
                matrix=mat,
                residues=residues,
                cmap=cmap,
                vmin=vmin,
                vmax=vmax,
                annotate=False,
                title=f"Anchor {anchor}, $i \\to i{sign_off}$",
                xlabel=f"$i{sign_off}$" if r_idx == n_rows - 1 else "",
                ylabel=f"Anchor {anchor} ($i$)" if c_idx == 0 else "",
            )

    fig.suptitle(f"Beta-Helix Pairwise Landscape ({metric})", fontsize=13, y=0.99)
    if last_img is not None:
        fig.subplots_adjust(right=0.90, wspace=0.28, hspace=0.30, top=0.90)
        cax = fig.add_axes([0.92, 0.12, 0.018, 0.75])
        cbar = fig.colorbar(last_img, cax=cax)
        cbar.set_label(metric_label, fontsize=10)
    else:
        fig.tight_layout()

    out_path = output_dir / f"heatmap_{metric}_overview.png"
    fig.savefig(out_path, bbox_inches="tight")
    plt.close(fig)
    return out_path


def plot_parity_scatter(
    matrices: dict[tuple[str, int], np.ndarray],
    output_dir: Path,
    metric: str,
    metric_label: str,
) -> Path | None:
    """Plot L-anchor vs D-anchor parity scatter colored by relative offset if both anchors exist."""
    offsets = sorted(
        {
            off
            for (_, off) in matrices.keys()
            if ("L", off) in matrices and ("D", off) in matrices
        }
    )
    if not offsets:
        return None

    fig, ax = plt.subplots(figsize=(6.4, 6.0), dpi=180)
    palette = plt.get_cmap("viridis")(np.linspace(0.05, 0.90, len(offsets)))
    all_vals: list[np.ndarray] = []

    for color, offset in zip(palette, offsets):
        mat_l = matrices[("L", offset)].ravel()
        mat_d = matrices[("D", offset)].ravel()
        mask = np.isfinite(mat_l) & np.isfinite(mat_d)
        if not np.any(mask):
            continue
        xl = mat_l[mask]
        yd = mat_d[mask]
        all_vals.extend([xl, yd])
        rmsd = float(np.sqrt(np.mean((xl - yd) ** 2)))
        ax.scatter(
            xl,
            yd,
            s=18,
            alpha=0.72,
            color=color,
            label=f"$i \\to i{offset:+d}$ (RMSD={rmsd:.3f})",
        )

    if not all_vals:
        plt.close(fig)
        return None

    stacked = np.concatenate(all_vals)
    lo = float(np.min(stacked))
    hi = float(np.max(stacked))
    pad = 0.04 * max(hi - lo, 1.0)
    ax.plot([lo - pad, hi + pad], [lo - pad, hi + pad], "k--", linewidth=1.0, label=r"$y = x$")
    ax.set_xlim(lo - pad, hi + pad)
    ax.set_ylim(lo - pad, hi + pad)
    ax.set_xlabel(f"L-anchor {metric_label}", fontsize=10)
    ax.set_ylabel(f"D-anchor {metric_label}", fontsize=10)
    ax.set_title(f"L-vs-D Anchor Chiral Parity ({metric})", fontsize=12)
    ax.legend(loc="best", fontsize=8, frameon=True)
    ax.grid(True, linestyle=":", alpha=0.4)
    fig.tight_layout()

    out_path = output_dir / f"parity_L_vs_D_{metric}.png"
    fig.savefig(out_path)
    plt.close(fig)
    return out_path


def parse_args() -> argparse.Namespace:
    """Parse CLI arguments for pair heatmap plotting."""
    parser = argparse.ArgumentParser(
        description="Plot beta-helix pairwise ddE heatmaps and L-vs-D parity checks."
    )
    parser.add_argument("csv_path", type=Path, help="Tidy CSV emitted by `probe-pairs`.")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("pair_heatmaps"),
        help="Directory for output PNG plots (default: pair_heatmaps).",
    )
    parser.add_argument(
        "--metric",
        type=str,
        default="ddE_dmc",
        choices=["ddE_dmc", "dE_vs_ala", "direct_total", "direct_sc_total"],
        help="Energy column to plot (default: ddE_dmc).",
    )
    parser.add_argument(
        "--cmap",
        type=str,
        default="cividis",
        help="Colorblind-friendly Matplotlib colormap (default: cividis).",
    )
    parser.add_argument(
        "--clip-percentile",
        type=float,
        default=95.0,
        help="Upper percentile clip for clash outliers (100 disables; default: 95).",
    )
    parser.add_argument("--vmin", type=float, default=None, help="Explicit color scale min.")
    parser.add_argument("--vmax", type=float, default=None, help="Explicit color scale max.")
    parser.add_argument(
        "--no-annotate",
        action="store_true",
        help="Disable numeric cell labels in individual heatmaps.",
    )
    return parser.parse_args()


def main() -> None:
    """CLI entrypoint for generating heatmaps and parity charts."""
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    residues, matrices = load_pair_table(args.csv_path, args.metric)
    label = METRIC_LABELS.get(args.metric, args.metric)

    single_paths = plot_single_heatmaps(
        residues=residues,
        matrices=matrices,
        output_dir=args.output_dir,
        metric=args.metric,
        metric_label=label,
        cmap=args.cmap,
        clip_percentile=args.clip_percentile,
        vmin_override=args.vmin,
        vmax_override=args.vmax,
        annotate=not args.no_annotate,
    )
    overview = plot_overview_grid(
        residues=residues,
        matrices=matrices,
        output_dir=args.output_dir,
        metric=args.metric,
        metric_label=label,
        cmap=args.cmap,
        clip_percentile=args.clip_percentile,
        vmin_override=args.vmin,
        vmax_override=args.vmax,
    )
    parity = plot_parity_scatter(
        matrices=matrices,
        output_dir=args.output_dir,
        metric=args.metric,
        metric_label=label,
    )

    for path in single_paths:
        print(f"Wrote {path}")
    if overview is not None:
        print(f"Wrote {overview}")
    if parity is not None:
        print(f"Wrote {parity}")


if __name__ == "__main__":
    main()
